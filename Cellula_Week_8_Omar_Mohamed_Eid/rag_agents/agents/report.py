"""Report Generator Agent: designs and writes a professional PDF report from the application's answers and analysis.

The agent has the full design toolkit (`tools/report_design.py`): fonts, font sizes, colours, spacing, page layout,
headers/footers, headings, rich text, lists, tables, callouts and charts. It decides the design (following the user's
instructions when given), places the content, reviews the outline, and the system renders the PDF.
If the model fails to produce any content, a clean default layout is used so the user always gets a report.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

from langchain_core.messages import HumanMessage, SystemMessage, ToolMessage

from ..config import Settings
from ..schemas import ReportTurn
from ..tools.report_design import ReportDesigner

_SYSTEM = """You are the Report Generator Agent. You turn the answers, analysis and results produced by a \
document question-answering system into a professional PDF report. You control the design with tools.

Workflow:
1. DESIGN FIRST. If the user gave design instructions (fonts, colours, sizes, layout, tone), follow them exactly with \
set_page_layout / set_fonts / set_font_sizes / set_colors / set_spacing / set_header_footer. Otherwise choose a clean, \
professional design: one sans or serif family, ~10.5pt body, a single accent colour, consistent heading sizes, a \
header and a footer with page numbers. Call list_fonts before choosing a font you are unsure about.
2. CONTENT. Start with add_title_block, then a short summary (add_callout works well for the key answer), then one \
section per question: add_heading, the answer, the analysis, calculations and comparisons. Use add_markdown to place \
the answer text exactly as given (it keeps bold, lists and tables and applies your theme). Use add_table for \
comparisons, add_bullets for calculations, and add_bar_chart only when the material contains at least two comparable \
numbers. Finish with a Sources section listing every source given.
3. REVIEW. Call review_report once, fix problems (low-contrast warnings, empty sections), then stop calling tools.

Content rules:
- Use ONLY the material provided. Never invent facts, numbers, quotes or sources. Keep numbers exactly as given.
- Keep citation markers like [1] and keep the Sources list consistent with them.
- If the material says information is missing or the evidence was insufficient, say so plainly in the report.
- Write in the language of the material. Professional tone, no emojis.
- If a tool returns an error or warning, correct it and continue."""


@dataclass
class ReportResult:
    path: Path
    title: str
    pages: int
    design_log: list[str] = field(default_factory=list)  # one line per design/content tool call
    used_fallback: bool = False


def _clip(text: str, limit: int) -> str:
    text = text or ""
    return text if len(text) <= limit else text[:limit] + " ...[truncated]"


def format_material(turns: list[ReportTurn]) -> str:
    blocks = []
    for i, t in enumerate(turns, 1):
        parts = [f"=== Exchange {i} ===", f"QUESTION: {t.question}", f"ANSWER (markdown):\n{_clip(t.answer, 6000)}"]
        if t.analysis:
            parts.append(f"ANALYSIS:\n{_clip(t.analysis, 4000)}")
        if t.calculations:
            parts.append("CALCULATIONS:\n" + "\n".join(f"- {_clip(c, 400)}" for c in t.calculations[:30]))
        if t.comparisons:
            parts.append("COMPARISONS:\n" + "\n".join(f"- {_clip(c, 400)}" for c in t.comparisons[:30]))
        if t.missing_information:
            parts.append("NOT FOUND IN THE DOCUMENTS: " + "; ".join(t.missing_information[:10]))
        if t.sources:
            parts.append("SOURCES:\n" + "\n".join(f"- {s}" for s in t.sources[:30]))
        blocks.append("\n".join(parts))
    return "\n\n".join(blocks)


def build_default_report(designer: ReportDesigner, turns: list[ReportTurn], title: str) -> None:
    """Deterministic fallback layout (also used by tests) - same toolkit, fixed design."""
    designer.set_header_footer(header_text=title, footer_text="Generated by the Cellula document assistant")
    designer.add_title_block(title, subtitle=f"{len(turns)} question(s) answered from the uploaded documents",
                             date=date.today().isoformat())
    for i, t in enumerate(turns, 1):
        designer.add_heading(f"{i}. {t.question}" if len(turns) > 1 else t.question, level=1, rule_below=True)
        designer.add_markdown(t.answer or "(no answer)", heading_offset=2)
        if t.analysis:
            designer.add_heading("Analysis", level=2)
            designer.add_markdown(t.analysis, heading_offset=2)
        if t.calculations:
            designer.add_heading("Calculations", level=2)
            designer.add_bullets(t.calculations)
        if t.comparisons:
            designer.add_heading("Comparisons", level=2)
            designer.add_bullets(t.comparisons)
        if t.missing_information:
            designer.add_callout("Not found in the documents: " + "; ".join(t.missing_information), kind="warning")
    sources = list(dict.fromkeys(s for t in turns for s in t.sources))
    if sources:
        designer.add_heading("Sources", level=1, rule_below=True)
        designer.add_bullets(sources)


class ReportAgent:
    def __init__(self, llm, settings: Settings):
        self.llm = llm
        self.settings = settings

    def generate(
        self, turns: list[ReportTurn], output_path: str | Path, instructions: str = "", title: str | None = None
    ) -> ReportResult:
        if not turns:
            raise ValueError("There is nothing to put in the report yet.")
        title = (title or "").strip() or (turns[0].question[:80] if len(turns) == 1 else "Document analysis report")
        designer = ReportDesigner(title=title)
        tools = designer.tools()
        by_name = {t.name: t for t in tools}
        log: list[str] = []

        messages = [
            SystemMessage(content=_SYSTEM),
            HumanMessage(
                content=(
                    f"Report title: {title}\nToday's date: {date.today().isoformat()}\n"
                    f"User's design instructions: {instructions.strip() or '(none - use a professional default design)'}\n\n"
                    f"MATERIAL:\n{format_material(turns)}"
                )
            ),
        ]
        used_fallback = False
        try:
            tool_llm = self.llm.bind_tools(tools)
            for _ in range(self.settings.report_max_tool_steps):
                ai = tool_llm.invoke(messages)
                messages.append(ai)
                calls = getattr(ai, "tool_calls", None) or []
                if not calls:
                    break
                for call in calls:
                    name, args = call["name"], call.get("args", {}) or {}
                    tool = by_name.get(name)
                    try:
                        output = tool.invoke(args) if tool else f"Unknown tool '{name}'."
                    except Exception as exc:  # validation errors etc. go back to the model so it can correct itself
                        output = f"Tool error: {exc}"
                    output = output if isinstance(output, str) else json.dumps(output, default=str)
                    log.append(f"{name}: {output[:200].splitlines()[0] if output else ''}")
                    messages.append(ToolMessage(content=output[:4000], tool_call_id=call.get("id", name), name=name))
        except Exception as exc:
            log.append(f"Agent error ({type(exc).__name__}: {exc}); using the default layout")

        if not designer.has_content():
            used_fallback = True
            log.append("The agent produced no content; the default layout was used.")
            designer = ReportDesigner(title=title)
            build_default_report(designer, turns, title)

        try:
            pages = designer.render(output_path)
        except Exception as exc:  # a design that cannot render (e.g. odd markup) must not lose the report
            if used_fallback:
                raise
            log.append(f"Rendering the agent's design failed ({type(exc).__name__}: {exc}); using the default layout.")
            used_fallback = True
            designer = ReportDesigner(title=title)
            build_default_report(designer, turns, title)
            pages = designer.render(output_path)
        return ReportResult(path=Path(output_path), title=title, pages=pages, design_log=log, used_fallback=used_fallback)
